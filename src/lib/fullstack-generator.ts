import { WebsiteProject, Section } from '@/types';
import { generateStandaloneHTML, generateReactComponentCode, renderSectionsHtml } from './code-generator';
import { generateCustomHooks } from './hooks-generator';

/**
 * Pillar 2: All-in-One Full-Stack Generation Engine
 * Synthesizes Next.js 15 App router files, API endpoints, PostgreSQL / Supabase DDL migration,
 * package.json, and WebContainer file tree representation.
 */

export interface FullStackProjectTree {
  fileTree: Record<string, string>;
  webContainerFileTree: Record<string, any>;
  dbSchema: string;
  apiRoutes: string[];
}

export function generateFullStackTree(project: WebsiteProject): FullStackProjectTree {
  const brandSlug = project.title.toLowerCase().replace(/[^a-z0-9]/g, '-');
  const hasAuth = project.sections.some(s => s.type === 'auth');
  const hasContact = project.sections.some(s => s.type === 'contact');
  const hasDashboard = project.sections.some(s => s.type === 'dashboard');

  // 1. SQL DDL Migration Schema (PostgreSQL / Supabase)
  const dbSchema = `-- Migration: 001_init_${brandSlug.replace(/-/g, '_')}.sql
-- Generated by AI Architect Studio for ${project.title}
-- Industry: ${project.industry}

-- Enable UUID extension
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- Table: users / profiles
CREATE TABLE IF NOT EXISTS public.profiles (
  id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
  email TEXT UNIQUE NOT NULL,
  full_name TEXT,
  avatar_url TEXT,
  role TEXT DEFAULT 'member',
  created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Table: inquiries / contact submissions
CREATE TABLE IF NOT EXISTS public.inquiries (
  id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
  name TEXT NOT NULL,
  email TEXT NOT NULL,
  phone TEXT,
  message TEXT NOT NULL,
  status TEXT DEFAULT 'pending',
  created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Table: telemetry / events
CREATE TABLE IF NOT EXISTS public.analytics_events (
  id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
  event_name TEXT NOT NULL,
  metadata JSONB DEFAULT '{}'::jsonb,
  ip_address TEXT,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Row Level Security (RLS) Policies
ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.inquiries ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.analytics_events ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Public inquiries insert" ON public.inquiries FOR INSERT WITH CHECK (true);
CREATE POLICY "Public analytics insert" ON public.analytics_events FOR INSERT WITH CHECK (true);
CREATE POLICY "Users can view own profile" ON public.profiles FOR SELECT USING (auth.uid() = id);
`;

  // 2. Next.js 15 API Route: /api/contact/route.ts
  const contactApiRoute = `import { NextRequest, NextResponse } from 'next/server';

export async function POST(req: NextRequest) {
  try {
    const body = await req.json();
    const { name, email, message, phone } = body;

    if (!name || !email || !message) {
      return NextResponse.json({ error: 'Missing required fields (name, email, message).' }, { status: 400 });
    }

    // Server-side audit & database insert simulation
    console.log('[API INTAKE] New inquiry for ${project.title}:', { name, email, phone });

    return NextResponse.json({
      success: true,
      message: 'Inquiry securely processed & recorded to PostgreSQL.',
      timestamp: new Date().toISOString(),
    });
  } catch (err: any) {
    return NextResponse.json({ error: err.message || 'Internal Server Error' }, { status: 500 });
  }
}
`;

  // 3. Next.js 15 API Route: /api/auth/route.ts
  const authApiRoute = `import { NextRequest, NextResponse } from 'next/server';

export async function POST(req: NextRequest) {
  try {
    const body = await req.json();
    const { email, password } = body;

    if (!email || !password) {
      return NextResponse.json({ error: 'Email and password required.' }, { status: 400 });
    }

    // Secure token generation simulation
    const token = 'jwt_' + Math.random().toString(36).substring(2) + Date.now();

    return NextResponse.json({
      success: true,
      user: { email, role: 'authenticated_member' },
      token,
      expiresIn: 3600,
    });
  } catch (err: any) {
    return NextResponse.json({ error: err.message }, { status: 500 });
  }
}
`;

  // 4. Standalone HTML + React components
  const standaloneHtml = generateStandaloneHTML(project);
  const reactCode = generateReactComponentCode(project);
  const jsonSchema = JSON.stringify(project, null, 2);

  const packageJson = JSON.stringify({
    name: brandSlug,
    version: '1.0.0',
    private: true,
    type: 'module',
    scripts: {
      dev: 'vite',
      build: 'vite build',
      preview: 'vite preview'
    },
    dependencies: {
      react: '^19.0.0',
      'react-dom': '^19.0.0',
      'lucide-react': '^1.55.0',
      '@supabase/supabase-js': '^2.48.0'
    },
    devDependencies: {
      '@vitejs/plugin-react': '^4.2.0',
      vite: '^5.1.0'
    }
  }, null, 2);

  const viteConfig = `import { defineConfig } from 'vite';
import react from '@vitejs/plugin-react';

export default defineConfig({
  plugins: [react()],
  server: {
    port: 5173,
    host: true
  }
});
`;

  const indexHtml = `<!DOCTYPE html>
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1.0" />
    <title>${project.title}</title>
    <script src="https://cdn.tailwindcss.com"></script>
  </head>
  <body class="bg-white text-black min-h-screen">
    <div id="root"></div>
    <script type="module" src="/src/main.jsx"></script>
  </body>
</html>
`;

  const mainJsx = `import React from 'react';
import ReactDOM from 'react-dom/client';
import App from './App.jsx';

ReactDOM.createRoot(document.getElementById('root')).render(
  <React.StrictMode>
    <App />
  </React.StrictMode>
);
`;

  const pageFiles: Record<string, string> = {};
  const pageRoutes: { slug: string; compName: string }[] = [];

  if (project.pages && project.pages.length > 0) {
    project.pages.forEach(p => {
      const cleanSlug = p.slug.replace(/^\//, '') || 'home';
      const compName = cleanSlug.charAt(0).toUpperCase() + cleanSlug.slice(1).replace(/[^a-zA-Z0-9]/g, '') + 'Page';
      const sectionsHtml = renderSectionsHtml(p.sections);
      const pageCode = `import React from 'react';

// Page: ${p.name} (${p.slug})
// ${p.title} - ${p.description || ''}
export default function ${compName}() {
  return (
    <main className="w-full">
      ${sectionsHtml}
    </main>
  );
}
`;
      pageFiles[`src/pages/${compName}.jsx`] = pageCode;
      pageRoutes.push({ slug: p.slug, compName });
    });
  }

  let appJsx = '';
  if (pageRoutes.length > 0) {
    const imports = pageRoutes.map(r => `import ${r.compName} from './pages/${r.compName}.jsx';`).join('\n');
    const routeMapping = pageRoutes.map(r => `  '${r.slug}': ${r.compName},`).join('\n');
    const defaultPage = pageRoutes[0].compName;

    appJsx = `import React, { useState, useEffect } from 'react';
${imports}

const routes = {
${routeMapping}
};

export default function App() {
  const [currentPath, setCurrentPath] = useState('${pageRoutes[0].slug}');

  useEffect(() => {
    const handleNavigation = () => {
      const hash = window.location.hash.replace('#', '') || '/';
      const clean = hash.startsWith('/') ? hash : '/' + hash;
      if (routes[clean]) {
        setCurrentPath(clean);
      }
    };
    handleNavigation();
    window.addEventListener('hashchange', handleNavigation);
    return () => window.removeEventListener('hashchange', handleNavigation);
  }, []);

  const ActiveComponent = routes[currentPath] || ${defaultPage};

  return (
    <div className="min-h-screen bg-white text-neutral-900 font-sans">
      <ActiveComponent />
    </div>
  );
}
`;
  } else {
    appJsx = `import React, { useState } from 'react';

export default function App() {
  const [inquirySent, setInquirySent] = useState(false);

  return (
    <div className="min-h-screen bg-white text-neutral-900 font-sans">
      ${standaloneHtml.replace(/<!DOCTYPE html>[\s\S]*?<body[^>]*>/i, '').replace(/<\/body>[\s\S]*?<\/html>/i, '')}
    </div>
  );
}
`;
  }

  const hooksCode = generateCustomHooks(project);

  // Materialized File Tree for export and WebContainer mount
  const fileTree: Record<string, string> = {
    'package.json': packageJson,
    'vite.config.js': viteConfig,
    'index.html': indexHtml,
    'src/main.jsx': mainJsx,
    'src/App.jsx': appJsx,
    ...pageFiles,
    'src/hooks/useSupabase.ts': hooksCode,
    'src/schema.json': jsonSchema,
    'supabase/migrations/001_init.sql': dbSchema,
    'src/app/api/contact/route.ts': contactApiRoute,
    'src/app/api/auth/route.ts': authApiRoute,
    'README.md': `# ${project.title}\n\nFull-Stack AI Generated Website with Next.js 15, PostgreSQL Schema, and WebContainers API.\n`
  };

  // WebContainer API Mount Structure ({ "file": { file: { contents: "..." } } })
  const pagesDir: Record<string, any> = {};
  Object.entries(pageFiles).forEach(([filePath, content]) => {
    const filename = filePath.split('/').pop()!;
    pagesDir[filename] = { file: { contents: content } };
  });

  const webContainerFileTree: Record<string, any> = {
    'package.json': {
      file: { contents: packageJson }
    },
    'vite.config.js': {
      file: { contents: viteConfig }
    },
    'index.html': {
      file: { contents: indexHtml }
    },
    'src': {
      directory: {
        'main.jsx': {
          file: { contents: mainJsx }
        },
        'App.jsx': {
          file: { contents: appJsx }
        },
        ...(Object.keys(pagesDir).length > 0 ? {
          'pages': {
            directory: pagesDir
          }
        } : {}),
        'hooks': {
          directory: {
            'useSupabase.ts': {
              file: { contents: hooksCode }
            }
          }
        },
        'schema.json': {
          file: { contents: jsonSchema }
        }
      }
    }
  };

  return {
    fileTree,
    webContainerFileTree,
    dbSchema,
    apiRoutes: ['/api/contact', '/api/auth']
  };
}
